# Ticket 57: turns the 1909 Waite–Smith scans (public domain; Wikimedia Commons, "RWS Tarot NN Name.jpg", "Wands01.jpg", …) into the game's
# card images: 260 px wide WebP in images/tarot/<id>.webp, and writes src/tarot/art.ts, which bundles them (wrangler.toml [[rules]] Data).
# Usage: python3 scripts/tarot-art.py <folder of scans named m00.jpg … pents14.jpg>
import os, sys
from PIL import Image
src = sys.argv[1]
ids = ["m%02d" % i for i in range(22)] + ["%s%02d" % (s, n) for s in ("wands", "cups", "swords", "pentacles") for n in range(1, 15)]
os.makedirs("images/tarot", exist_ok=True)
for i in ids:
    name = i.replace("pentacles", "pents") + ".jpg"
    im = Image.open(os.path.join(src, name)).convert("RGB")
    w = 260
    h = round(im.height * w / im.width)
    im.resize((w, h), Image.LANCZOS).save("images/tarot/%s.webp" % i, "WEBP", quality=56, method=6)
lines = ["// Generated by scripts/tarot-art.py (ticket 57): the 78 card images of the 1909 Waite–Smith deck (Pamela Colman Smith, public domain),",
         "// 260 px WebP, bundled into the Worker as Data modules. Do not edit by hand.", ""]
for i in ids:
    lines.append('import %s from "../../images/tarot/%s.webp";' % (i, i))
lines += ["", "export const ART: Record<string, ArrayBuffer> = { %s };" % ", ".join(ids), ""]
open("src/tarot/art.ts", "w").write("\n".join(lines))
print("done", len(ids))
